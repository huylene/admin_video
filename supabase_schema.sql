-- 1. EXTENSIONS
create extension if not exists pgcrypto;

-- 2. TABLES

-- Profiles Table (1-1 with auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  email text not null unique,
  role text not null default 'USER' check (role in ('ADMIN', 'USER')),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Video Categories Table
create table if not exists public.video_categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  description text,
  created_at timestamptz not null default now()
);

-- Videos Table
create table if not exists public.videos (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text unique,
  description text,
  thumbnail_path text,
  video_path text not null,
  views bigint not null default 0,
  duration_seconds integer,
  category_id uuid references public.video_categories(id) on delete set null,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

-- Video Views Log Table (Used for analytics and trends)
create table if not exists public.video_views (
  id bigint generated by default as identity primary key,
  video_id uuid not null references public.videos(id) on delete cascade,
  viewer_id uuid references public.profiles(id) on delete set null,
  viewed_at timestamptz not null default now(),
  session_id text
);

-- Video Tags Table
create table if not exists public.video_tags (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  created_at timestamptz not null default now()
);

-- Video Tag Mapping Table
create table if not exists public.video_tag_map (
  video_id uuid not null references public.videos(id) on delete cascade,
  tag_id uuid not null references public.video_tags(id) on delete cascade,
  primary key (video_id, tag_id)
);

-- Storage Assets Table (Tracks physical file sizes for storage metrics)
create table if not exists public.storage_assets (
  id uuid primary key default gen_random_uuid(),
  video_id uuid not null references public.videos(id) on delete cascade,
  bucket text not null,
  path text not null,
  asset_type text not null check (asset_type in ('video', 'thumbnail')),
  size_bytes bigint not null default 0,
  mime_type text,
  created_at timestamptz not null default now()
);

-- 3. INDEXES
create index if not exists idx_video_views_video_id on public.video_views(video_id);
create index if not exists idx_video_views_viewed_at on public.video_views(viewed_at);
create index if not exists idx_videos_category_id on public.videos(category_id);
create index if not exists idx_videos_views on public.videos(views desc);
create index if not exists idx_storage_assets_video_id on public.storage_assets(video_id);

-- 4. PROFILE AUTO-CREATE TRIGGER
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, username, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)),
    new.email,
    'USER'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- 5. ADMIN CHECK HELPER FUNCTION
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.role = 'ADMIN'
  );
$$;

